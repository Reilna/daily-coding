CREATE TABLE api_loans (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           book_instance_id BIGINT NOT NULL,
                           user_id BIGINT NOT NULL,
                           loaned_at TIMESTAMPTZ NOT NULL,
                           returned_at TIMESTAMPTZ,

                           CONSTRAINT fk_loans_book_instance
                               FOREIGN KEY (book_instance_id)
                                   REFERENCES api_book_instances(id),

                           CONSTRAINT fk_loans_user
                               FOREIGN KEY (user_id)
                                   REFERENCES api_users(id)
);

CREATE UNIQUE INDEX uq_api_loans_active_instance
    ON api_loans(book_instance_id)
    WHERE returned_at IS NULL;

CREATE INDEX idx_api_loans_user_id
    ON api_loans(user_id);