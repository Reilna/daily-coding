CREATE TABLE api_book_instances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL,
    inventory_number VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT fk_book_instances_book
        FOREIGN KEY (book_id)
        REFERENCES api_books(id)
);

CREATE INDEX idx_book_instances_book_id ON api_book_instances(book_id);